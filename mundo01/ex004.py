test = input('Insira qualquer coisa: ')

print('O tipo primitivo é:',type(test))
print('É maiscula:',(test.isupper()))
print('É minuscula:',(test.islower()))
print('É alpha:',(test.isalpha()))
print('É alphanúmerico:',(test.isalnum()))
print('É númerico:',(test.isnumeric()))
print('É decimal:',(test.isdecimal()))
